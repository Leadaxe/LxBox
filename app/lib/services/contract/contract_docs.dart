/// §460 W2b — адреса страниц документации контракта.
///
/// Страницы собирает генератор лаунчера по реестру, а лежат они копией в
/// нашем репозитории (`docs/contract/`, кладётся `tool/sync_contract.sh`).
/// Ссылка ведёт к нам, а не в репозиторий лаунчера: там страницы живут
/// впереди контракта, под который собран установленный APK, и текст на них
/// описывал бы поведение, которого у пользователя ещё нет.
///
/// В APK страницы не едут: текст, причина и способ исправления лежат в
/// реестре и показываются офлайн. Ссылка — для того, кто хочет страницу
/// целиком.
library;

/// Ветка `main`: релизный APK собран с неё, и зеркало в ней соответствует
/// тому контракту, по которому приложение судит узел. Ссылка на `develop`
/// показывала бы страницы вперёд установленной версии.
const _docsBase =
    'https://github.com/Leadaxe/LxBox/blob/main/docs/contract';

/// Страница кода предупреждения с якорем на его разделе.
///
/// Якорь — сам код: `gendocs` ставит перед заголовком раздела явный
/// `<a id="<code>"></a>` (страж — `test/contract/docs_mirror_test.dart`).
/// Кода, которого на странице нет, ссылка не знает — она приведёт в начало
/// файла, и это лучше, чем её отсутствие: список кодов там же.
String contractWarningDocUrl(String code) => '$_docsBase/warnings.md#$code';
