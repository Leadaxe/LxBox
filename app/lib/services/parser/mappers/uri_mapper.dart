/// §472 шаг 2 — маппер «ссылка → сырая карта sing-box».
///
/// Разделение труда в конвейере (спека 472, раздел 2):
///
/// ```
/// ссылка ─маппер→ сырая карта ─санитайзер по реестру→ чистая карта
///                                      │
///                                      └→ warnings (code, path, value)
/// ```
///
/// **Маппер переводит диалект и не судит значения.** Он знает, что `sni=`,
/// `peer=` и `host=` адресуют одно поле `tls.server_name`, что `?ed=N` в
/// хвосте пути — это два отдельных поля тела, что `headerType=http` поверх
/// `tcp` зовётся транспортом `http`. Годен ли отпечаток, лежит ли `short_id`
/// в hex, не длиннее ли путь допустимого — решает санитайзер по реестру, и
/// решает ОДИН раз на все входы.
///
/// Граница проверяемая: маппер не заводит `NodeWarning` о значении. Его
/// собственные предупреждения — только о переводе, который ЧТО-ТО потерял или
/// переложил ([UriMapping.warnings]): `ws_early_data_converted` говорит, что
/// путь уехал в тело не буквально, `ech_ignored` — что параметр не перенесён
/// вовсе. Такое знает только маппер: в теле этих значений уже нет, и
/// санитайзеру о них сказать нечего.
library;

import '../../../models/node_warning.dart';
import '../../contract/body_sanitizer.dart' show BodySource;

/// Результат перевода одной ссылки.
final class UriMapping {
  const UriMapping({
    required this.body,
    required this.label,
    this.warnings = const [],
    this.extensionFields = const {},
    this.wsEarlyDataHeaderImplicit = false,
    this.tagAddress,
    this.kindIsAwg = false,
    this.kinds = const {},
    this.bodySource = BodySource.other,
  });

  /// Сырая карта sing-box: то, что ссылка сказала, в ключах тела. Ещё не
  /// судимая — в ней законно лежит и мусор, который снимет санитайзер.
  ///
  /// `tag` сюда НЕ кладётся: его считает конвейер из [label] по общему
  /// правилу ([tagFromLabel]), и санитайзеру он не принадлежит (ключ сборки,
  /// `_kBuildManagedKeys`).
  final Map<String, dynamic> body;

  /// Имя узла из фрагмента ссылки, уже раскодированное. Пустое — имени нет.
  final String label;

  /// Предупреждения САМОГО перевода (не о значениях). См. doc библиотеки.
  final List<NodeWarning> warnings;

  /// §453 — dial-поля keep-alive, которые ссылка везёт отдельными
  /// параметрами (`tcp_keep_alive`, `tcp_keep_alive_interval`,
  /// `disable_tcp_keep_alive`).
  ///
  /// §474 (контракт 1.1.6) — обхода санитайзера здесь БОЛЬШЕ НЕТ. Пока реестр
  /// числил эти поля строками `skipped`, они дописывались в тело после судьи
  /// и мимо него: иначе санитайзер снял бы их как `unknown_key` — код о
  /// «неизвестном ключе» на поле, которое ядро принимает (`DialerOptions`), а
  /// человек написал сам. Теперь `dialer.json` описывает их полями, конвейер
  /// вливает эту карту в тело ДО санитайзинга, и судятся они наравне с
  /// прочими.
  ///
  /// Отдельным полем карта осталась потому, что источник у неё отдельный: это
  /// параметры ссылки вне схемы протокола, и складывает их общий помощник
  /// (`tcpKeepAliveMapFromQuery`), а не маппер схемы.
  final Map<String, dynamic> extensionFields;

  /// §472 шаг 7 — адрес для ТЕГ-ФОЛБЭКА, когда в корне тела его нет.
  ///
  /// Безымянная ссылка получает тег `<тип>-<адрес>-<порт>`, и конвейер берёт
  /// адрес из `server`/`server_port` тела. У ENDPOINT-схем (wireguard, AWG)
  /// таких ключей в корне не бывает вовсе: адрес живёт внутри `peers[]`, а
  /// `emitWireguard` корневых `server`/`server_port` не пишет. Без этого поля
  /// безымянный WG-узел получил бы тег `wireguard--0` вместо
  /// `wireguard-h.example-51820` — то есть у живых узлов сменилась бы
  /// identity (тег И ЕСТЬ identity, `node_hash.dart`).
  ///
  /// `null` — адрес берётся из корня тела, как у всех прочих схем.
  final (String, int)? tagAddress;

  /// §463/§473 — ссылка ПРОСИЛА AmneziaWG, даже если ни одного годного
  /// AWG-поля в теле не осталось.
  ///
  /// Правила `mtu` реестра (`default_when`, `max_when`) судят род узла по
  /// НАЛИЧИЮ КЛЮЧА в теле (`when.any_set`), и почти всегда этого довольно.
  /// Но ссылка может попросить AWG и не донести ни одного годного поля
  /// (`jc=abc` вместе с одиноким `jmin` — кейсы корпуса
  /// `awg_bad_numeric_skipped`, `awg_jc_invalid_dropped`): тело у такого узла
  /// от обычного WireGuard неотличимо, а корпус ждёт `mtu: 1280`. Ссылка
  /// просила AmneziaWG, и потолок — свойство ЗАПРОШЕННОГО протокола, а не
  /// уцелевших полей (§463, то же основание, что у рукописного `isAwg`).
  ///
  /// Знает об этом только маппер: до санитайзера значения уже разобраны, а в
  /// теле следа не осталось. Само число берёт конвейер из реестра.
  final bool kindIsAwg;

  /// §480 — рода узла, объявленные ВХОДОМ (`kind_when` секции реестра).
  ///
  /// То же, что [kindIsAwg], но именами ИЗ ДАННЫХ: движок имён схем не знает
  /// и отдаёт строки как есть, а толкует их вызывающий. Рукописные мапперы
  /// ставят [kindIsAwg] напрямую и это поле не заполняют.
  final Set<String> kinds;

  /// §103 D-008 — заголовок early data подставлен САМОЙ формой записи
  /// (`?ed=N` хвостом пути), а не написан автором ссылки.
  ///
  /// В теле этой разницы нет: `early_data_header_name` там стоит в обоих
  /// случаях, и корпус требует именно так. Но `toUri()` обязан её знать —
  /// Go никогда не пишет `eh=` обратно для path-tail формы
  /// (`shareuri_helpers.go`), и без флага round-trip добавлял бы в ссылку
  /// параметр, которого в ней не было. Знает об этом только маппер: он один
  /// видел исходную форму.
  final bool wsEarlyDataHeaderImplicit;

  /// §480 — ВХОД, которым тело приехало, названный самой секцией-маппером
  /// (`body_source`).
  ///
  /// Санитайзер судит по нему `max_when.except_sources` — единственное
  /// место контракта, где вход влияет на РЕЗУЛЬТАТ, а не только на разбор.
  /// До этого конвейер передавал туда заглушку [BodySource.other] на всех
  /// входах, кроме sing-box-JSON: правило работало вслепую, и стоило реестру
  /// перечислить в исключениях любой другой вход, как тела у нас и у
  /// лаунчера разошлись бы молча.
  ///
  /// [BodySource.other] по умолчанию — для рукописных мапперов, за которыми
  /// секции ещё нет: там вход себя не называет, и поведение остаётся прежним.
  final BodySource bodySource;
}

/// Перевод ссылки одной схемы. `null` — ссылка не разбирается вовсе
/// (нет хоста, нет обязательного userinfo): тем же `null`, каким отвечал
/// прежний парсер, конвейер отдаёт «узла нет».
///
/// Аргумент — ИСХОДНЫЙ ТЕКСТ ссылки, а не `Uri` (§472 шаг 4). Шаги 2 и 3
/// принимали `Uri`: у trojan и vless ссылка и есть URI, и разбор строки —
/// работа платформы. У vmess и shadowsocks это не так. `vmess://` везёт
/// base64-полезную нагрузку там, где у URI стоит authority, а `Uri` приводит
/// authority к нижнему регистру — base64 после этого не декодируется вовсе
/// (`eyJ2IjoiMiJ9` → `eyj2ijoimij9`). Та же беда у legacy-формы
/// `ss://base64(method:password@host:port)`. Поэтому решать, читается ли
/// ссылка как URI, стало делом самого маппера: trojan и vless зовут
/// `Uri.tryParse` первой строкой, vmess и shadowsocks работают с текстом.
typedef UriMapper = UriMapping? Function(String uri);
