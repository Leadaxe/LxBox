package com.leadaxe.lxbox.vpn

/// §747 — учёт стартов одного экземпляра сервиса: какой остановкой какой старт
/// можно снести. Чистая логика без Android (JVM-тест).
///
/// Система нумерует каждую команду старта (`startId`) в момент, когда её
/// **запросили**, а сервису отдаёт позже. `stopSelf()` без номера сносит
/// сервис вместе со стартом, который уже запрошен, но ещё не доставлен: так
/// остановка прошлого туннеля убивала новый старт, пришедший сразу после
/// объявления `Stopped` (а с foreground-стартом — и весь процесс:
/// `ForegroundServiceDidNotStartInTimeException`).
///
/// Правило: сервис останавливает себя только с номером ([stopToken]) —
/// `stopSelf(startId)` система исполняет, лишь если более новых стартов не
/// запрошено. Номер — последний **доставленный** старт: он покрывает и
/// старты, которые сервис принял, но не стал исполнять (пришли во время
/// остановки), иначе такой сервис остался бы висеть запущенным.
///
/// [generation] — номер исполняемого старта туннеля. Фоновая доводка прошлой
/// остановки (force-stop объявляет `Stopped` раньше, чем закончит) сверяет
/// его перед тем, как останавливать сервис: если начался новый старт, сервис
/// уже принадлежит ему.
class StartLedger {
    @Volatile
    private var lastDelivered = 0

    @Volatile
    var generation = 0
        private set

    /// `onStartCommand(startId)` — старт доставлен (исполнен он будет или нет).
    fun delivered(startId: Int) {
        if (startId > lastDelivered) lastDelivered = startId
    }

    /// Начато исполнение старта туннеля; возвращает его поколение.
    fun begin(): Int = ++generation

    /// Номер для `stopSelf(startId)`: остановить всё доставленное, не трогая
    /// запрошенное позже.
    fun stopToken(): Int = lastDelivered

    /// Остановка поколения [gen] ещё вправе останавливать сервис.
    fun owns(gen: Int): Boolean = gen == generation

    companion object {
        /// То, что делает система с `stopSelf(token)`: сервис останавливается,
        /// только если [lastRequested] — номер последнего запрошенного старта —
        /// совпадает с [token]. Для теста правила.
        fun systemStops(token: Int, lastRequested: Int): Boolean = token == lastRequested
    }
}
